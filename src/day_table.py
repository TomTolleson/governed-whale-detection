"""Build the deployment-day table and the eligible-day summary.

    python -m src.day_table --actor <name>

Inputs (offline): data/labels/*.csv and data/audio_listing.json from
`python -m src.label_survey fetch`. Rules are in docs/labeling_rules.md.
"""

import argparse
import hashlib
import json
from collections import Counter

import pandas as pd

from src.audit import log_event
from src.label_survey import (DEPLOYMENTS, LABEL_DIR, LISTING_PATH, ROOT, SITES,
                              file_intervals, hours_per_day)

DAY_TABLE = ROOT / "data" / "day_table.csv"
SUMMARY_DOC = ROOT / "docs" / "eligible_summary.md"

MIN_ELIGIBLE_HOURS = 20.0
FULL_DAY_HOURS = 24.0 - 1 / 60  # a day missing less than 1 minute counts as full
MIN_ABSENT = 5                  # flag deployments with fewer absent eligible days
NEAR_THRESHOLD_H = 1.0          # report days within this many hours of the 20 h cut
COLUMNS = ["site", "deployment", "date", "label", "audio_hours", "is_partial_day",
           "no_audio", "is_changeover_day", "eligible"]


def build_day_table(labels: dict, listing: dict) -> pd.DataFrame:
    """labels: {"sb01_01": DataFrame(ISOStartTime, Presence)}, listing: {"sb01_01": [[name, size], ...]}."""
    rows = []
    for key, df in labels.items():
        site, dep = key.split("_")
        intervals, _ = file_intervals(listing[key])
        hpd = hours_per_day(intervals)
        for day, presence in zip(pd.to_datetime(df["ISOStartTime"]).dt.date, df["Presence"]):
            rows.append({"site": site, "deployment": dep, "date": day.isoformat(),
                         "label": int(presence), "audio_hours": round(hpd.get(day, 0.0), 3)})
    t = pd.DataFrame(rows)
    t["no_audio"] = t["audio_hours"] == 0
    t["is_partial_day"] = (t["audio_hours"] > 0) & (t["audio_hours"] < FULL_DAY_HOURS)
    per_site_day = t.groupby(["site", "date"])["deployment"].transform("nunique")
    t["is_changeover_day"] = per_site_day > 1
    # Rule from the brief: eligible only if audio_hours >= 20 and not no_audio.
    t["eligible"] = (t["audio_hours"] >= MIN_ELIGIBLE_HOURS) & ~t["no_audio"]
    return t[COLUMNS]


def exclusion_reason(row) -> str | None:
    if row["eligible"]:
        return None
    if row["no_audio"]:
        return "no_audio"
    return "audio_hours_lt_20"


def load_inputs():
    listing = json.loads(LISTING_PATH.read_text())
    labels = {f"{s}_{d}": pd.read_csv(LABEL_DIR / f"{s}_{d}.csv") for s in SITES for d in DEPLOYMENTS}
    return labels, listing


def render_summary(t: pd.DataFrame) -> str:
    e = t[t["eligible"]]
    lines = ["| Deployment | Labelled days | Eligible days | Present | Absent | Absent share | Flag |",
             "|---|---|---|---|---|---|---|"]

    def row(name, all_rows, el, bold=False):
        n, p = len(el), int(el["label"].sum())
        a = n - p
        flag = f"⚠ < {MIN_ABSENT} absent" if a < MIN_ABSENT and not bold else ""
        b = "**" if bold else ""
        share = f"{a / n:.1%}" if n else "–"
        return f"| {b}{name}{b} | {len(all_rows)} | {b}{n}{b} | {p} | {a} | {share} | {flag} |"

    flagged = []
    for site in SITES:
        for dep in DEPLOYMENTS:
            sel = (t["site"] == site) & (t["deployment"] == dep)
            el = e[(e["site"] == site) & (e["deployment"] == dep)]
            lines.append(row(f"{site}_{dep}", t[sel], el))
            if len(el) - el["label"].sum() < MIN_ABSENT:
                flagged.append((f"{site}_{dep}", len(el), int(len(el) - el["label"].sum())))
        lines.append(row(site, t[t["site"] == site], e[e["site"] == site], bold=True))
    lines.append(row("ALL", t, e, bold=True))

    reasons = Counter(r for r in t.apply(exclusion_reason, axis=1) if r)
    near = t[(t["audio_hours"] - MIN_ELIGIBLE_HOURS).abs() < NEAR_THRESHOLD_H]
    elig_changeover = e[e["is_changeover_day"]]
    with_audio = t[~t["no_audio"]]
    last_days = with_audio.loc[with_audio.groupby(["site", "deployment"])["date"].idxmax()]
    last_max = last_days.loc[last_days["audio_hours"].idxmax()]
    flagged_txt = "\n".join(f"- **{k}**: {a} absent of {n} eligible days" for k, n, a in flagged) or "- none"
    near_txt = ", ".join(f"{r.site}_{r.deployment} {r.date} ({r.audio_hours:.2f} h)" for r in near.itertuples()) or "none"

    return f"""# Eligible-day summary

Generated by `python -m src.day_table` from `data/day_table.csv` (one row per deployment-day with a label).
Rules: `docs/labeling_rules.md`. A day is **eligible** only if `audio_hours >= 20` and not `no_audio`.

## Per deployment

{chr(10).join(lines)}

## Deployments with fewer than {MIN_ABSENT} absent eligible days

{flagged_txt}

## Excluded days

| Reason | Days |
|---|---|
| no_audio (label row, no audio file covers the day) | {reasons.get('no_audio', 0)} |
| audio_hours < 20 (partial first/last day of a deployment) | {reasons.get('audio_hours_lt_20', 0)} |
| **total excluded** | **{sum(reasons.values())}** of {len(t)} labelled days |

- Changeover days (labelled by two deployments): {int(t['is_changeover_day'].sum())} rows; of these
  **{len(elig_changeover)} are eligible**, so no changeover day enters the eligible set and the
  conflicting labels from `docs/label_survey.md` do not affect it.
- Eligible rows are unique per site and date: {not e.duplicated(['site', 'date']).any()}.
- Days within ±{NEAR_THRESHOLD_H:g} h of the 20 h cut (where estimate error could flip eligibility): {near_txt}.

## How reliable is `audio_hours`?

See `docs/header_check.md`. In 13 real FLAC headers, the duration of every file that has a next file
matched its name-based estimate to within about 1 s for normal files. `_Post-clip` files were 8–16 s
shorter than their slot. The size-based estimate for a deployment's **last file** was off by −191 s to
+2,147 s (up to 0.6 h). That error only affects the final day. The longest final day is
{last_max.audio_hours:.2f} h ({last_max.site}_{last_max.deployment} {last_max.date}), so a final day would
only become eligible if its last-file estimate were short by more than
{20 - last_max.audio_hours:.2f} h. The largest error among the 5 sampled last files was 0.6 h. The other 31
last files were not checked.
"""


def main(actor: str):
    labels, listing = load_inputs()
    t = build_day_table(labels, listing)
    t.to_csv(DAY_TABLE, index=False)
    reasons = Counter(r for r in t.apply(exclusion_reason, axis=1) if r)
    log_event(actor, "write_day_table", {
        "dest": str(DAY_TABLE.relative_to(ROOT)), "rows": len(t),
        "sha256": hashlib.sha256(DAY_TABLE.read_bytes()).hexdigest(),
        "eligible": int(t["eligible"].sum()),
        "excluded_by_reason": dict(reasons),
        "excluded_total": sum(reasons.values()),
        "info": {"changeover_rows": int(t["is_changeover_day"].sum()),
                 "partial_rows": int(t["is_partial_day"].sum())},
    })
    SUMMARY_DOC.write_text(render_summary(t))
    log_event(actor, "write_eligible_summary", {
        "dest": str(SUMMARY_DOC.relative_to(ROOT)),
        "sha256": hashlib.sha256(SUMMARY_DOC.read_bytes()).hexdigest()})
    print(f"{len(t)} rows, {int(t['eligible'].sum())} eligible, excluded {dict(reasons)}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--actor", required=True)
    main(ap.parse_args().actor)
