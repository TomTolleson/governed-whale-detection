"""Candidate train/validation vs test splits over eligible days (no choice made).

    python -m src.split_candidates --actor <name>   # writes docs/split_candidates.md
"""

import argparse
import hashlib

import pandas as pd

from src.audit import log_event
from src.label_survey import ROOT

DAY_TABLE = ROOT / "data" / "day_table.csv"
OUT_DOC = ROOT / "docs" / "split_candidates.md"
SEASONS = ["DJF", "MAM", "JJA", "SON"]
MONTH_SEASON = {12: "DJF", 1: "DJF", 2: "DJF", 3: "MAM", 4: "MAM", 5: "MAM",
                6: "JJA", 7: "JJA", 8: "JJA", 9: "SON", 10: "SON", 11: "SON"}


def load():
    df = pd.read_csv(DAY_TABLE, dtype={"deployment": str})
    df = df[df.eligible].copy()
    df["date"] = pd.to_datetime(df.date)
    df["season"] = df.date.dt.month.map(MONTH_SEASON)
    df["dep"] = df.deployment.astype(int)
    return df


def splits(df):
    s12 = df.site.isin(["sb01", "sb02"])
    return {
        "A": ("Held-out site", [
            ("train/validation", "sb01 + sb02, all deployments", df[s12]),
            ("test", "sb03, all deployments", df[df.site == "sb03"]),
        ]),
        "B": ("Latest deployments in time (sb01 + sb02 only; sb03 unused)", [
            ("train/validation", "sb01 + sb02, deployments 01-09", df[s12 & (df.dep <= 9)]),
            ("test", "sb01 + sb02, deployments 10-12", df[s12 & (df.dep >= 10)]),
        ]),
    }


def stats(part):
    present = int((part.label == 1).sum())
    row = {"days": len(part), "present": present, "absent": len(part) - present,
           "first": part.date.min().date().isoformat(), "last": part.date.max().date().isoformat()}
    for s in SEASONS:
        p = part[part.season == s]
        row[s] = (len(p), int((p.label == 1).sum()), int((p.label == 0).sum()))
    return row


def render(df, result):
    out = ["# Candidate splits", "",
           f"Generated by `python -m src.split_candidates` from `data/day_table.csv`. Only **eligible** days "
           f"({len(df)}) are counted (rule: `docs/labeling_rules.md`). Seasons by UTC calendar month: "
           "DJF = Dec-Feb, MAM = Mar-May, JJA = Jun-Aug, SON = Sep-Nov. No split is chosen here.", "",
           "Season cells read `days (present / absent)`.", ""]
    hdr = ("| Part | Contents | Days | Present | Absent | Absent share | Dates | "
           + " | ".join(SEASONS) + " |")
    for key, (title, parts) in splits(df).items():
        out += [f"## Split {key}: {title}", "", hdr, "|" + "---|" * (7 + len(SEASONS))]
        for part_name, desc, part in parts:
            r = result[key][part_name]
            seasons = " | ".join(f"{r[s][0]} ({r[s][1]} / {r[s][2]})" for s in SEASONS)
            out.append(f"| {part_name} | {desc} | {r['days']} | {r['present']} | {r['absent']} | "
                       f"{r['absent'] / r['days']:.1%} | {r['first']} to {r['last']} | {seasons} |")
        tv, te = result[key]["train/validation"], result[key]["test"]
        out += ["", f"Test share of the split's days: {te['days'] / (tv['days'] + te['days']):.1%}.", ""]

    out += ["## Notes", "",
            "- Split B leaves out all sb03 days, so it uses fewer days in total than Split A.",
            "- Train/validation is reported as one pool; how it is divided into train and validation "
            "is not decided here.",
            "- Deployments with fewer than 5 absent eligible days are listed in `docs/eligible_summary.md`.", ""]
    return "\n".join(out)


def run(actor):
    df = load()
    result = {key: {name: stats(part) for name, _, part in parts}
              for key, (_, parts) in splits(df).items()}
    text = render(df, result)
    OUT_DOC.write_text(text)
    log_event(actor, "write_split_candidates", {
        "dest": str(OUT_DOC.relative_to(ROOT)),
        "sha256": hashlib.sha256(text.encode()).hexdigest(),
        "source": "data/day_table.csv",
        "source_sha256": hashlib.sha256(DAY_TABLE.read_bytes()).hexdigest(),
        "summary": {k: {p: {x: v[x] for x in ("days", "present", "absent")} for p, v in parts.items()}
                    for k, parts in result.items()},
        "split_chosen": None})


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--actor", required=True)
    run(ap.parse_args().actor)
